const LANGUAGE_STORAGE_KEY = 'rotiwrap-language';
const DEFAULT_LANGUAGE = 'id';
const header = document.querySelector('.site-header');
const menuToggle = document.querySelector('.menu-toggle');
const menuToggleLabel = menuToggle.querySelector('.sr-only');
const mainNav = document.querySelector('.main-nav');
const languageButtons = document.querySelectorAll('[data-lang]');
let currentLanguage = DEFAULT_LANGUAGE;

function savedLanguage() {
  try {
    const language = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return Object.prototype.hasOwnProperty.call(translations, language) ? language : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

function updateMenuLabel() {
  const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
  menuToggleLabel.textContent = translations[currentLanguage][isOpen ? 'menuCloseLabel' : 'menuOpenLabel'];
}

function applyLanguage(language, { persist = false } = {}) {
  const scrollPosition = { x: window.scrollX, y: window.scrollY };
  currentLanguage = Object.prototype.hasOwnProperty.call(translations, language) ? language : DEFAULT_LANGUAGE;
  const copy = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;
  document.title = copy.metaTitle;
  document.querySelector('meta[name="description"]').setAttribute('content', copy.metaDescription);
  document.querySelector('meta[property="og:title"]').setAttribute('content', copy.metaTitle);
  document.querySelector('meta[property="og:description"]').setAttribute('content', copy.metaOgDescription);
  document.querySelector('meta[property="og:locale"]').setAttribute('content', copy.metaOgLocale);

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = copy[element.dataset.i18n];
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    element.innerHTML = copy[element.dataset.i18nHtml];
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.setAttribute('alt', copy[element.dataset.i18nAlt]);
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', copy[element.dataset.i18nAriaLabel]);
  });

  languageButtons.forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === currentLanguage));
  });
  updateMenuLabel();
  window.scrollTo(scrollPosition.x, scrollPosition.y);

  if (persist) {
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, currentLanguage);
    } catch {
      // The language still changes for this visit when storage is unavailable.
    }
  }
}

function setMenu(open) {
  menuToggle.setAttribute('aria-expanded', String(open));
  mainNav.classList.toggle('open', open);
  header.classList.toggle('menu-open', open);
  document.body.style.overflow = open ? 'hidden' : '';
  updateMenuLabel();
}

function updateHeader() {
  header.classList.toggle('scrolled', window.scrollY > 20);
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang, { persist: true }));
});

menuToggle.addEventListener('click', () => {
  setMenu(menuToggle.getAttribute('aria-expanded') !== 'true');
});

mainNav.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => setMenu(false));
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') {
    setMenu(false);
    menuToggle.focus();
  }
});

window.addEventListener('resize', () => {
  if (window.innerWidth > 860) setMenu(false);
});

window.addEventListener('scroll', updateHeader, { passive: true });

applyLanguage(savedLanguage());
updateHeader();
document.getElementById('year').textContent = new Date().getFullYear();
